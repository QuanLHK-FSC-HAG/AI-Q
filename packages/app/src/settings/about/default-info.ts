function bytes(input: string) {
  return new TextEncoder().encode(input)
}

function fnv1a(input: string) {
  let h = 2166136261
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return (h >>> 0).toString(16).padStart(8, "0")
}

function b64encode(input: string) {
  const b = bytes(input)
  let bin = ""
  for (let i = 0; i < b.length; i++) bin += String.fromCharCode(b[i]!)
  return btoa(bin)
}

function b64decode(input: string) {
  const bin = atob(input)
  const b = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) b[i] = bin.charCodeAt(i)
  return new TextDecoder().decode(b)
}

function xor(input: string, key: string) {
  const a = bytes(input)
  const k = bytes(key)
  const out = new Uint8Array(a.length)
  for (let i = 0; i < a.length; i++) out[i] = a[i]! ^ k[i % k.length]!
  let bin = ""
  for (let i = 0; i < out.length; i++) bin += String.fromCharCode(out[i]!)
  return btoa(bin)
}

function xorDecode(input: string, key: string) {
  const bin = atob(input)
  const k = bytes(key)
  const out = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i) ^ k[i % k.length]!
  return new TextDecoder().decode(out)
}

const KEY = "AIQ-P0-QuanLHK-2026"

export type StoredProfile = {
  userName: string
  termsVersion?: string
  privacyVersion?: string
  acceptedAt?: string
}

export function sealProfile(profile: StoredProfile) {
  const payload = JSON.stringify(profile)
  const data = xor(payload, KEY)
  const sum = fnv1a(data + "|" + KEY)
  return b64encode(JSON.stringify({ v: 1, data, sum }))
}

export function openProfile(raw: string | null | undefined): StoredProfile | null {
  if (!raw) return null
  try {
    const outer = b64decode(raw)
    const parsed = JSON.parse(outer) as { v?: number; data?: string; sum?: string }
    if (parsed?.v !== 1 || typeof parsed.data !== "string" || typeof parsed.sum !== "string") return null
    const sum = fnv1a(parsed.data + "|" + KEY)
    if (sum !== parsed.sum) return null
    const payload = xorDecode(parsed.data, KEY)
    const value = JSON.parse(payload) as {
      userName?: unknown
      termsVersion?: unknown
      privacyVersion?: unknown
      acceptedAt?: unknown
    }
    if (typeof value.userName !== "string") return null
    return {
      userName: value.userName,
      ...(typeof value.termsVersion === "string" ? { termsVersion: value.termsVersion } : {}),
      ...(typeof value.privacyVersion === "string" ? { privacyVersion: value.privacyVersion } : {}),
      ...(typeof value.acceptedAt === "string" ? { acceptedAt: value.acceptedAt } : {}),
    }
  } catch {
    return null
  }
}

export function displayVersion(userName?: string) {
  const name = userName?.trim()
  if (!name) return VERSION_BASE
  return VERSION_TEMPLATE.replace("{userName}", name)
}

// Precomputed integrity marker for bundled defaults (informational/check).
const bundledPayload = b64encode(JSON.stringify(DEFAULT_P0))
export const BUNDLED_INFO = {
  payload: bundledPayload,
  sum: fnv1a(bundledPayload),
}

export function readBundledInfo() {
  try {
    if (fnv1a(BUNDLED_INFO.payload) !== BUNDLED_INFO.sum) return { ...DEFAULT_P0 }
    const text = b64decode(BUNDLED_INFO.payload)
    const parsed = JSON.parse(text) as typeof DEFAULT_P0
    if (parsed?.app !== APP_NAME || parsed?.author !== AUTHOR) return { ...DEFAULT_P0 }
    return parsed
  } catch {
    return { ...DEFAULT_P0 }
  }
}
